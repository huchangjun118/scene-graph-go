// Package scenegraph 提供场景图与空间查询内核，供上层渲染与交互逻辑复用。
//
// # 坐标约定
//
//   - 采用右手坐标系，向量与矩阵运算均使用 float64。
//   - Mat4 为列主序 4x4 仿射矩阵，点的变换为 v' = M * v。
//   - 节点局部变换为 TRS：M_local = T * R * S（先缩放，再旋转，再平移）。
//   - 世界变换沿层级复合：M_world = M_parentWorld * M_local，
//     根节点的父变换为单位矩阵。
//   - 包围盒为轴对齐盒（AABB），Min/Max 为闭区间端点；
//     节点的世界包围盒由其局部包围盒 8 个角点经世界变换后重取包围得到。
//
// # 变换传播与增量更新
//
// 修改节点局部变换（SetLocal）或改变挂载关系（Attach/Detach）后，
// 仅该节点子树的世界变换被重算，其余节点的世界变换与查询结果不变。
// 挂载形成环（目标父节点是被挂载节点自身或其后代）时操作被拒绝，
// 场景保持原状。
//
// # 查询语义
//
//   - QueryRegion：返回世界包围盒与区域相交（闭区间，接触算相交）的节点。
//   - QueryFrustum：返回世界包围盒与视锥相交或在视锥内的节点；
//     判定为保守判定（仅当包围盒完全位于某一裁剪平面外侧时才排除）。
//   - Raycast：返回命中世界包围盒的最近节点，命中距离取进入参数 tNear。
//     边界行为均为确定行为：射线起点在盒内时 tNear = 0；射线与盒
//     相切视为命中；节点尺度退化（某轴缩放为 0，盒退化为面/线/点）
//     时仍按退化后的盒做 slab 相交；多个节点命中距离相同时按场景
//     遍历顺序取先者；射线方向无需归一化，t 与方向尺度一致。
//   - 所有查询返回节点 ID，顺序为场景确定遍历顺序
//     （根列表按成为根的顺序，子节点按挂载顺序，先序遍历），
//     在固定输入序列与随机种子下逐条可复现。
//   - 查询结果反映最近一次已提交的变换。
//
// # 并发模型
//
// Scene 为多读单写：查询持有读锁，变更持有写锁。读者看到的始终是
// 最近一次完整提交的状态，不会读到撕裂的世界变换。Update 提供事务
// 语义：批量变更在私有副本上执行，fn 返回错误（取消）时场景保持原状，
// 不会停留在中间状态；fn 成功时变更原子提交。
//
// # 导出与恢复
//
// Export 输出确定顺序的 JSON；Import 原子生效且幂等——对同一份数据
// 重复导入不会产生重复节点，恢复后层级结构、节点标识与查询结果与
// 导出前一致。导入采用合并语义：场景中已存在但不在导入数据中的节点
// 保持不变。
